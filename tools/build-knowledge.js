// Builds js/knowledge.js (loaded by the app, works offline and from file://) from the two research files:
//   js/knowledge.json  — goals, swaps, pairings, cooking tips, unsung heroes (each with an evidence level and source)
//   js/swapsdata.json  — nutrients per 100 g and Malaysian prices per kg, each with its source
// Run: npm run data   (a unit test fails if js/knowledge.js is out of date)
const fs = require("node:fs");
const path = require("node:path");
const ROOT = path.resolve(__dirname, "..");
const K = JSON.parse(fs.readFileSync(path.join(ROOT, "js/knowledge.json"), "utf8"));
const D = JSON.parse(fs.readFileSync(path.join(ROOT, "js/swapsdata.json"), "utf8"));

// USDA mirror pages → the official FoodData Central page for the same FDC id
const officialUrl = url => {
  const m = /getfoodfacts\.com\/food\/.*-(\d{5,7})\/?$/.exec(url || "");
  return m ? `https://fdc.nal.usda.gov/food-details/${m[1]}/nutrients` : url;
};
const fixEvidence = ev => ev && ({ ...ev, url: officialUrl(ev.url),
  source: String(ev.source || "").replace(/;?\s*prices? from swapsdata\.json(\s*\([^)]*\))?/g, "").trim() });

// Swap names → ids in swapsdata, so each swap can show the price sources too
const NAME_ID = { blueberries: "blueberries", guava: "guava", kale: "kale", kailan: "kailan", kangkung: "kangkung", spinach: "spinach", bayam: "bayam",
  broccoli: "broccoli", quinoa: "quinoa", dhal: "dhal", tempeh: "tempeh", salmon: "salmon", "ikan kembung": "kembung", watercress: "watercress",
  "pulut hitam": null, orange: null, "brown rice": "brownrice" };
const idFor = name => { const k = String(name).toLowerCase().replace(/\s*\(.*\)\s*/g, "").trim(); return NAME_ID[k] !== undefined ? NAME_ID[k] : null; };

const walk = v => Array.isArray(v) ? v.map(walk) : v && typeof v === "object"
  ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, k === "evidence" ? fixEvidence(x) : k === "url" ? officialUrl(x) : walk(x)]))
  : v;
const knowledge = walk(K);
knowledge.swaps = knowledge.swaps.map(s => ({ ...s, fromId: idFor(s.from), toId: idFor(s.to) }));
const swapdata = walk(D);
swapdata.foods = swapdata.foods.map(f => ({ ...f, nutrientSource: f.nutrientSource && { ...f.nutrientSource, url: officialUrl(f.nutrientSource.url) } }));

const out = `// GENERATED by tools/build-knowledge.js from js/knowledge.json and js/swapsdata.json. Do not edit by hand.
const KNOWLEDGE = ${JSON.stringify(knowledge)};
const SWAPDATA = ${JSON.stringify(swapdata)};
if (typeof module !== "undefined") module.exports = { KNOWLEDGE, SWAPDATA };
`;
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(path.join(ROOT, "js/knowledge.js")) ? fs.readFileSync(path.join(ROOT, "js/knowledge.js"), "utf8") : "";
  process.exit(cur === out ? 0 : 1);
}
fs.writeFileSync(path.join(ROOT, "js/knowledge.js"), out);
console.log("js/knowledge.js written:", knowledge.goals.length, "goals,", knowledge.swaps.length, "swaps,", knowledge.pairings.length, "pairings,",
  knowledge.cooking.length, "cooking tips,", knowledge.heroes.length, "heroes,", swapdata.foods.length, "foods");
